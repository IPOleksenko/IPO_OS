#!/usr/bin/env python3
"""
tools/generate_ksyms.py
Extracts ALL defined function symbols (global, static, weak, assembly) from
the pre-linked kernel ELF image and generates a compiled kernel symbol table (C source file).
"""

import sys
import os
import argparse
import subprocess
import re

def is_valid_c_ident(name: str) -> bool:
    return bool(re.match(r'^[a-zA-Z_][a-zA-Z0-9_]*$', name))

def extract_symbols_from_elf(elf_path: str):
    symbols = {}
    cmd = ["nm", "-n", elf_path]
    try:
        proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=True)
        for line in proc.stdout.splitlines():
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) >= 3:
                addr_str, stype, sname = parts[0], parts[1], parts[2]
                if stype != "U":
                    # Avoid characters that cannot form valid C string literals
                    if '"' in sname or '\\' in sname:
                        continue
                    try:
                        addr = int(addr_str, 16)
                        # Prefer global/weak symbol over local static duplicate
                        if sname not in symbols or (stype.isupper() and not symbols[sname][1].isupper()):
                            symbols[sname] = (addr, stype)
                    except ValueError:
                        continue
    except subprocess.CalledProcessError as e:
        print(f"[generate_ksyms] Error running nm on ELF: {e.stderr}", file=sys.stderr)
        sys.exit(1)

    return {k: v[0] for k, v in symbols.items()}

def extract_symbols_from_objects(obj_files):
    symbols = set()
    if not obj_files:
        return symbols

    cmd = ["nm", "-g", "--defined-only"] + obj_files
    try:
        proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=True)
        for line in proc.stdout.splitlines():
            line = line.strip()
            if not line or line.endswith(":"):
                continue
            parts = line.split()
            if len(parts) >= 3:
                stype, sname = parts[1], parts[2]
                if stype != "U":
                    if is_valid_c_ident(sname):
                        symbols.add(sname)
    except subprocess.CalledProcessError as e:
        print(f"[generate_ksyms] Error running nm: {e.stderr}", file=sys.stderr)
        sys.exit(1)

    return symbols

def generate_c_file_from_elf(sym_map, output_path):
    sorted_syms = sorted(sym_map.keys())

    lines = []
    lines.append("/* Autogenerated by tools/generate_ksyms.py - DO NOT EDIT MANUALLY */")
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    const char *name;")
    lines.append("    void       *addr;")
    lines.append("} kernel_sym_entry_t;")
    lines.append("")
    lines.append("/* Exported kernel symbol table sorted alphabetically by name */")
    lines.append("const kernel_sym_entry_t s_kernel_syms[] = {")
    for sym in sorted_syms:
        addr = sym_map[sym]
        lines.append(f"    {{\"{sym}\", (void *)0x{addr:08x}U}},")
    lines.append("    {NULL, NULL}")
    lines.append("};")
    lines.append("")
    lines.append(f"const size_t s_kernel_syms_count = {len(sorted_syms)};")
    lines.append("")

    content = "\n".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"[generate_ksyms] Generated {output_path} with {len(sorted_syms)} exported kernel symbols.")

def generate_c_file_from_objects(symbols, output_path):
    sorted_syms = sorted(symbols)

    lines = []
    lines.append("/* Autogenerated by tools/generate_ksyms.py - DO NOT EDIT MANUALLY */")
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("typedef struct {")
    lines.append("    const char *name;")
    lines.append("    void       *addr;")
    lines.append("} kernel_sym_entry_t;")
    lines.append("")
    lines.append("/* Forward declarations of exported kernel functions */")
    for sym in sorted_syms:
        if sym == "s_kernel_syms":
            continue
        elif sym == "s_kernel_syms_count":
            lines.append("extern const size_t s_kernel_syms_count;")
        else:
            lines.append(f"extern void {sym}(void);")
    lines.append("")
    lines.append("/* Exported kernel symbol table sorted alphabetically by name */")
    lines.append("const kernel_sym_entry_t s_kernel_syms[] = {")
    for sym in sorted_syms:
        if sym == "s_kernel_syms_count":
            lines.append(f"    {{\"{sym}\", (void *)&{sym}}},")
        else:
            lines.append(f"    {{\"{sym}\", (void *){sym}}},")
    lines.append("    {NULL, NULL}")
    lines.append("};")
    lines.append("")
    lines.append(f"const size_t s_kernel_syms_count = {len(sorted_syms)};")
    lines.append("")

    content = "\n".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"[generate_ksyms] Generated {output_path} with {len(sorted_syms)} exported kernel symbols.")

def main():
    parser = argparse.ArgumentParser(description="Generate kernel symbol table")
    parser.add_argument("-o", "--output", required=True, help="Output C source file")
    parser.add_argument("-e", "--elf", help="Pre-linked kernel ELF executable to extract all symbols with exact addresses")
    parser.add_argument("objects", nargs="*", help="Object files or directories containing object files")

    args = parser.parse_args()

    if args.elf:
        sym_map = extract_symbols_from_elf(args.elf)
        generate_c_file_from_elf(sym_map, args.output)
        return

    obj_files = []
    for item in args.objects:
        if os.path.isdir(item):
            for root, _, files in os.walk(item):
                for f in files:
                    if f.endswith(".o") and not f.endswith("kernel_syms_autogen.o"):
                        obj_files.append(os.path.join(root, f))
        elif os.path.isfile(item):
            if not item.endswith("kernel_syms_autogen.o"):
                obj_files.append(item)

    if not obj_files:
        print("[generate_ksyms] No object files found!", file=sys.stderr)
        sys.exit(1)

    symbols = extract_symbols_from_objects(obj_files)
    generate_c_file_from_objects(symbols, args.output)

if __name__ == "__main__":
    main()
